export function renderSpecsReadme(): string {
  return `# knowledge/specs/ — as-built record

Every delivered spec lands here as the final task of its own implementation
(AGENTS.md rule 7). This directory is **append-only**: never rewrite a past
spec — if reality diverged from the approved design, append a \`## Deviations\`
section to the existing file.

This is the loop that makes context compound. The next spec retrieves these.
`;
}

/** The complete setup-PR payload for one repo. */
export function renderScaffold(input: {
  repoName: string;
  projectName: string;
  isPrimary: boolean;
  stack: DetectedStack;
  topLevelDirs: string[];
  entryPoints: string[];
  glossaryTerms: string[];
  date: string;
  agentsMd: string;
  architectureMd?: string;
  conventionsMd?: string;
  glossaryMd?: string;
}): ScaffoldFile[] {
  return [
    { path: 'AGENTS.md', content: input.agentsMd },
    { path: 'CLAUDE.md', content: renderClaudeMdRef() },
    {
      path: 'knowledge/README.md',
      content: renderKnowledgeReadme({
        repoName: input.repoName,
        stack: input.stack,
        projectName: input.projectName,
      }),
    },
    {
      path: 'knowledge/architecture.md',
      content:
        input.architectureMd ??
        renderArchitecture({
          repoName: input.repoName,
          stack: input.stack,
          topLevelDirs: input.topLevelDirs,
          entryPoints: input.entryPoints,
        }),
    },
    {
      path: 'knowledge/conventions.md',
      content:
        input.conventionsMd ??
        renderConventions({ repoName: input.repoName, stack: input.stack }),
    },
    {
      path: 'knowledge/glossary.md',
      content:
        input.glossaryMd ??
        renderGlossary({ repoName: input.repoName, terms: input.glossaryTerms }),
    },
    {
      path: 'knowledge/decisions/0001-adopt-spec-driven.md',
      content: renderAdoptionAdr({ projectName: input.projectName, date: input.date }),
    },
    {
      path: 'knowledge/runbooks/local-dev.md',
      content: renderLocalDevRunbook({ repoName: input.repoName, stack: input.stack }),
    },
    { path: 'knowledge/runbooks/deploy.md', content: renderDeployRunbook({ repoName: input.repoName }) },
    { path: 'knowledge/specs/README.md', content: renderSpecsReadme() },
  ];
}

function renderClaudeMdRef(): string {
  return `# CLAUDE.md

@AGENTS.md

<!--
  specd emits both files by design (D6): AGENTS.md is canonical and read by
  most agents; this file is a thin pointer so Claude Code picks up the same
  rules natively. Edit AGENTS.md — this file needs no maintenance.
-->
`;
}

/** The setup PR description. It says exactly what the drafts are worth (§6). */
export function renderSetupPrBody(input: {
  repoName: string;
  projectName: string;
  fileCount: number;
  unverifiedCount: number;
  stackLine: string;
}): string {
  return `## specd setup — review me, then merge to adopt

This PR installs the working agreements and knowledge base for **${input.projectName}**.

**${input.fileCount} files**, all marked \`DRAFT\`. Detected stack: ${input.stackLine}.

### What is in here

- \`AGENTS.md\` — working agreements for AI agents (knowledge-first, spec-driven,
  as-built specs). \`CLAUDE.md\` imports it so Claude Code picks up the same rules.
- \`knowledge/\` — the curated wiki agents must read before implementing anything.

### Read this before you merge

These docs were drafted from a **read-only repo scan**. The scan can see your
file tree, manifests and config; it cannot see your intent. Every claim it
could not ground is marked **UNVERIFIED** — there are **${input.unverifiedCount}** of them.

**Do not treat generated text as verified.** Review it the way you would review
a new hire's first architecture write-up: the shape is useful, the details need
your judgement. Merging is adopting.

### After merging

1. Fill in the \`UNVERIFIED\` markers — the glossary and architecture boundaries
   pay for themselves fastest.
2. Write or import your first ticket.
3. Generate your first spec, review it, and stamp it.

_Opened by specd · git stays the source of truth for knowledge; the platform
only holds a derived index._
`;
}
