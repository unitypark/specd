import { type DetectedStack, describeStack } from './stack.js';

/**
 * The knowledge/ scaffold. Every generated doc carries a DRAFT banner and
 * per-claim UNVERIFIED markers — the wizard must not lie (§6). Credibility
 * with senior engineers is won or lost in these files.
 */

export const DRAFT_BANNER = `> **status: DRAFT — review before trusting.** Generated by specd from a
> read-only repo scan. Claims the agent could not ground in the code are
> marked \`UNVERIFIED\`. Merging this PR is how you adopt it; edit freely.`;

export interface ScaffoldFile {
  path: string;
  content: string;
}

export function renderKnowledgeReadme(input: {
  repoName: string;
  stack: DetectedStack;
  projectName: string;
}): string {
  return `# knowledge/ — start here

${DRAFT_BANNER}

This directory is the curated context for **${input.repoName}** (project:
${input.projectName}). Agents read it before writing code; humans read it before
reviewing. It is the source of truth — specd only holds a derived index.

## Reading order

| Read this | When |
| --- | --- |
| \`architecture.md\` | Before any change that crosses a module boundary |
| \`conventions.md\` | Before writing code — lint rules, layout, test patterns |
| \`glossary.md\` | When a domain term is unfamiliar |
| \`decisions/\` | Before revisiting a choice someone already made |
| \`runbooks/\` | When running, deploying or debugging locally |
| \`specs/\` | Before designing something adjacent — every delivered spec lands here |

## How this stays alive

- Docs ride the change: update them in the **same PR** as the code (AGENTS.md rule 3).
- Delivered specs are appended to \`specs/\` automatically as the last task of every spec.
- specd re-indexes on merge and flags docs that have drifted from the code.

Stack: ${describeStack(input.stack) || '_not detected — please fill in_'}
`;
}

export function renderArchitecture(input: {
  repoName: string;
  stack: DetectedStack;
  topLevelDirs: string[];
  entryPoints: string[];
}): string {
  const { repoName, stack, topLevelDirs, entryPoints } = input;
  const dirRows = topLevelDirs.length
    ? topLevelDirs.map((d) => `| \`${d}/\` | UNVERIFIED — describe what lives here |`).join('\n')
    : '| _(no directories detected)_ | |';

  return `# Architecture — ${repoName}

${DRAFT_BANNER}

## Shape

- **Stack:** ${describeStack(stack) || '_not detected_'}  [detected]
- **Entry points:** ${entryPoints.length ? entryPoints.map((e) => `\`${e}\``).join(', ') : '_UNVERIFIED — none detected_'}

## Layout

| Path | Responsibility |
| --- | --- |
${dirRows}

## Boundaries

UNVERIFIED — the repo scan can see the file tree but not the intent behind it.
Describe here: which modules may call which, where transactions begin and end,
and what crosses a network boundary. This is the section agents lean on most.

## Data

UNVERIFIED — name the stores, what owns each table/collection, and the
migration story.

## Integrations

UNVERIFIED — external services this repo calls, and what happens when they fail.
`;
}

export function renderConventions(input: { repoName: string; stack: DetectedStack }): string {
  const { stack } = input;
  return `# Conventions — ${input.repoName}

${DRAFT_BANNER}

## Verify before opening a PR

\`\`\`
${stack.verifyCommand ?? '# UNVERIFIED — no verify command detected; add yours here'}
\`\`\`

## Detected

| Thing | Value |
| --- | --- |
| Language | ${stack.language} |
| Framework | ${stack.framework ?? '_none detected_'} |
| Package manager | ${stack.packageManager ?? '_none detected_'} |
| Test runner | ${stack.testRunner ?? '_none detected_'} |
| Linter | ${stack.linter ?? '_none detected_'} |

## Code style

UNVERIFIED — the scan reads config files, not taste. Record the decisions a
reviewer would otherwise repeat in every review: naming, file layout, error
handling, when to add an abstraction.

## Tests

UNVERIFIED — what must have a test, what may not, and how to run a subset.

## Git

UNVERIFIED — branch naming, commit style, review expectations. Note that specd
requires \`spec/<id>-<slug>\` branches for spec-driven work (AGENTS.md rule 6).
`;
}

export function renderGlossary(input: { repoName: string; terms: string[] }): string {
  const rows = input.terms.length
    ? input.terms.map((t) => `| **${t}** | UNVERIFIED — define in one sentence |`).join('\n')
    : '| _(no terms mined)_ | |';

  return `# Glossary — ${input.repoName}

${DRAFT_BANNER}

Domain terms mined from code and docs. The agent can spot the words; only a
human can say what they mean. Filling this in is the highest-leverage hour you
will spend on this directory.

| Term | Meaning |
| --- | --- |
${rows}
`;
}

export function renderAdoptionAdr(input: { projectName: string; date: string }): string {
  return `# 0001 — Adopt spec-driven delivery

- **Status:** accepted
- **Date:** ${input.date}
- **Project:** ${input.projectName}

## Context

AI coding agents produce inconsistent results when every session rediscovers the
codebase from raw source. Context evaporates when a session ends, conventions get
reinvented, and assumptions ship silently.

## Decision

Work reaches coding agents as a **human-approved spec**, never as a bare prompt.
Agents read \`knowledge/\` first, cite what they relied on, and file the as-built
spec back into \`knowledge/specs/\` in the same PR as the code.

The approval gate is structural: no agent may approve its own input.

## Consequences

- Every change is traceable to an approved spec and a named approver.
- \`knowledge/\` must be maintained in the same PR as the code it describes,
  or it rots and the next spec is grounded in fiction.
- Prompt injection via ticket text cannot reach a code-writing agent without
  surviving human review first.
`;
}

